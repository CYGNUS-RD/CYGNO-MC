inline double Basis(const double* t, int i, int degree, double x)
{
  if (degree == 0) return t[i] <= x && x < t[i+1] ? 1. : 0.;
  double left = 0., right = 0.;
  if (t[i+degree] > t[i])
    left = (x-t[i])/(t[i+degree]-t[i]) * Basis(t,i,degree-1,x);
  if (t[i+degree+1] > t[i+1])
    right = (t[i+degree+1]-x)/(t[i+degree+1]-t[i+1]) * Basis(t,i+1,degree-1,x);
  return left + right;
}

// Strict fitted domain: any continuation for transport belongs in CYGNOHit.
inline Response Evaluate(const Model& model, double energy_keV)
{
  if (!std::isfinite(energy_keV) || energy_keV < model.lo || energy_keV > model.hi)
    throw std::out_of_range("CYGNO SRIM QF requires 0.025--3000 keV per ion");
  const double x0 = std::log(energy_keV);
  // Cox-de Boor basis intervals are half-open: evaluate the upper endpoint
  // from the left, as in the frozen SRIM evaluator.
  const double x = x0 == model.knots[model.count+3]
      ? std::nextafter(x0, model.knots[0]) : x0;
  const double* t = model.knots;
  double q = 0., dq_dlogE = 0.;
  for (int i = 0; i < model.count; ++i) {
    const double b = Basis(t,i,3,x);
    double db = 0.;
    if (t[i+3] > t[i]) db += 3./(t[i+3]-t[i]) * Basis(t,i,2,x);
    if (t[i+4] > t[i+1]) db -= 3./(t[i+4]-t[i+1]) * Basis(t,i+1,2,x);
    q += model.coefficients[i] * b;
    dq_dlogE += model.coefficients[i] * db;
  }
  // d(E*QF)/dE = QF + dQF/dlnE; may exceed one and must not be clipped.
  return {q, q + dq_dlogE};
}
